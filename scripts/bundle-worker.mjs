// Bundle the multi-module Worker source into one ESM file for upload.
//
// The Worker is deliberately dependency-free plain ESM (no wrangler, no esbuild),
// so a tiny deterministic concatenator is enough: modules are emitted in import
// order, `import` statements are dropped and `export` keywords are removed.
// The result is what `wrangler deploy` would produce for this trivial graph.
//
// Usage: node scripts/bundle-worker.mjs [--check]

import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'packages', 'directory-worker', 'src');
const OUT = path.join(ROOT, 'packages', 'directory-worker', 'dist', 'worker.js');

const MODULES = ['crypto.js', 'storage.js', 'app.js', 'index.js'];

function stripImports(code, file) {
  const withoutImports = code
    .replace(/^import\s*\{[\s\S]*?\}\s*from\s*['"][^'"]+['"];?\s*$/gm, '')
    .replace(/^import\s+[^;'\n]+?;?\s*$/gm, '');
  if (/\bfrom\s+['"]/.test(withoutImports)) {
    const stillImported = withoutImports.match(/^import[\s\S]*?from\s*['"][^'"]+['"];?/gm);
    if (stillImported) throw new Error(`${file}: unresolved import left: ${stillImported[0]}`);
  }
  return withoutImports;
}

function stripExports(code) {
  return code.replace(/^export\s+(?=(?:const|let|var|function|async\s+function|class)\b)/gm, '');
}

function transformIndex(code) {
  let out = code.replace(/^export\s+default\s+\{/m, 'const __workerEntry = {');
  if (!out.includes('const __workerEntry = {')) throw new Error('index.js: default export not found');
  out += '\nexport default __workerEntry;\n';
  return out;
}

const parts = ['// Auto-generated by scripts/bundle-worker.mjs - do not edit by hand.'];
for (const name of MODULES) {
  const file = path.join(SRC, name);
  let code = fs.readFileSync(file, 'utf8');
  code = stripImports(code, name);
  code = stripExports(code);
  if (name === 'index.js') code = transformIndex(code);
  // Sanity: no relative imports may survive in the bundle.
  if (/^import\s/m.test(code) || /from\s+['"]\.\//.test(code)) {
    throw new Error(`${name}: import escaped bundling`);
  }
  parts.push(`// ---- ${name} ${'-'.repeat(Math.max(3, 60 - name.length))}`);
  parts.push(code.trimEnd());
}

const bundle = `${parts.join('\n\n')}\n`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, bundle);

console.log(`bundled ${MODULES.length} modules -> ${path.relative(ROOT, OUT)} (${bundle.length} bytes)`);

if (process.argv.includes('--check')) {
  const url = `file:///${OUT.replace(/\\/g, '/')}`;
  const mod = await import(url);
  if (typeof mod.default?.fetch !== 'function') throw new Error('bundle has no default.fetch');
  const health = await mod.default.fetch(new Request('http://bundle.local/api/health'), {});
  const body = await health.json();
  if (health.status !== 200 || !body.ok) throw new Error(`bundle health failed: ${health.status}`);
  const created = await mod.default.fetch(
    new Request('http://bundle.local/api/pools', {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ name: 'bundle-check', deviceName: 'node' }),
    }),
    {},
  );
  const pool = await created.json();
  if (created.status !== 201 || !pool.pool?.joinCode) {
    throw new Error(`bundle create pool failed: ${created.status} ${JSON.stringify(pool).slice(0, 200)}`);
  }
  console.log(`bundle check OK: health + createPool (pool ${pool.pool.id})`);
}
